_progress_callback = None

def set_progress_callback(callback):
    global _progress_callback
    _progress_callback = callback

def update_progress(current, total, message):
    if _progress_callback:
        try:
            _progress_callback(current, total, message)
        except Exception:
            pass

SOURCE_EXTENSIONS = {
    '.py', '.js', '.ts', '.jsx', '.tsx', '.java', '.c', '.cpp', '.h', '.cs',
    '.html', '.css', '.php', '.rb', '.go', '.rs', '.swift', '.kt', '.scala',
    '.sh', '.bat', '.sql', '.r', '.m', '.json', '.xml', '.yaml', '.yml',
    '.txt', '.md', '.ipynb'
}

HIGH_VALUE_EXTENSIONS = {
    '.py', '.js', '.ts', '.jsx', '.tsx', '.java', '.c', '.cpp', '.cs', '.go', '.rb', '.php'
}

AI_MARKERS = [
    "as an ai language model", "generated by chatgpt", "openai", "chatgpt", "claude", "llm",
    "here is the code", "certainly!", "hope this helps", "absolutely!", "i've provided",
    "this code snippet", "gpt-4", "gpt-3.5", "ai assistant", "i see you want",
    "ai-generated", "language model", "provided as is", "based on the requirements",
    "to implement this", "the following code", "as specified", "model: gpt", "model: claude",
    "generated by ai", "generated using ai", "this task was completed by"
]

def hash_file(filepath):
    try:
        hasher = hashlib.md5()
        with open(filepath, 'rb') as f:
            while chunk := f.read(65536):
                hasher.update(chunk)
        return hasher.hexdigest()
    except Exception:
        return None

class _StructuralASTShingler(python_ast.NodeVisitor):
    """Visits AST nodes and records their structural type sequence."""
    def __init__(self):
        self.seq = []
    def generic_visit(self, node):
        self.seq.append(type(node).__name__)
        super().generic_visit(node)

def _get_ast_shingles(content: str):
    """Extracts 4-gram structural AST shingles from Python code."""
    try:
        tree = python_ast.parse(content)
        v = _StructuralASTShingler()
        v.generic_visit(tree)
        seq = v.seq
        if len(seq) >= 4:
            return set(zip(seq, seq[1:], seq[2:], seq[3:]))
        elif seq:
            return set([tuple(seq)])
        return set()
    except Exception:
        return None

def process_single_repo(repo_meta):
    """Indexes files, hashes, ASTs, lines, and AI signatures for a single student."""
    folder = repo_meta['folder']
    download_folder = repo_meta['download_folder']
    full_path = os.path.join(download_folder, folder)

    scan_path = full_path
    try:
        subdirs = [d for d in os.listdir(scan_path) if os.path.isdir(os.path.join(scan_path, d)) and d not in ('.git', '__pycache__')]
        if len(subdirs) == 1:
            scan_path = os.path.join(scan_path, subdirs[0])
    except Exception:
        pass

    parts = [p.strip() for p in folder.split(' - ')]
    sheet = parts[0] if len(parts) > 0 else 'Unknown'
    reg_no = parts[1] if len(parts) > 1 else 'Unknown'
    name = parts[2] if len(parts) > 2 else 'Unknown'
    source = parts[3] if len(parts) > 3 else 'Unknown'

    fh = {}
    fpaths = {}
    ast_map = {}
    lines_set = set()
    ai_found = []

    for root, dirs, files in os.walk(scan_path):
        dirs[:] = [d for d in dirs if d not in ('.git', 'node_modules', '__pycache__', '.venv', 'venv', 'dist', 'build', '.idea', '.vscode')]
        for fname in files:
            ext = os.path.splitext(fname)[1].lower()
            if ext not in SOURCE_EXTENSIONS:
                continue

            abs_path = os.path.join(root, fname)
            rel_path = os.path.relpath(abs_path, scan_path).replace("\\", "/")

            try:
                sz = os.path.getsize(abs_path)
                if sz > 250000:  # Skip generated/binary bundles > 250KB
                    continue
            except Exception:
                continue

            h = hash_file(abs_path)
            if not h:
                continue

            fh[rel_path] = h
            fpaths[rel_path] = abs_path

            try:
                with open(abs_path, 'r', encoding='utf-8', errors='ignore') as fp:
                    content = fp.read()
            except Exception:
                continue

            c_lower = content.lower()
            for m in AI_MARKERS:
                if m in c_lower:
                    ai_found.append(m)

            if ext == '.py':
                sh = _get_ast_shingles(content)
                if sh:
                    ast_map[rel_path] = sh

            # Line shingles (32-bit hashes of stripped non-comment lines)
            for l in content.splitlines():
                s = l.strip().lower()
                if len(s) > 10 and not s.startswith(('#', '//', '/*', '*', '<!--', '--')):
                    lines_set.add(hash(s) & 0xFFFFFFFF)

    return {
        'folder': folder,
        'scan_path': os.path.abspath(scan_path),
        'sheet': sheet,
        'reg_no': reg_no,
        'name': name,
        'source': source,
        'file_hashes': fh,
        'hash_set': set(fh.values()),
        'file_paths': fpaths,
        'ast_map': ast_map,
        'lines': lines_set,
        'file_count': len(fh),
        'ai_score': min(100, len(ai_found) * 25),
        'ai_markers': list(set(ai_found))
    }

def run_plagiarism_analysis(download_folder):
    """
    Executes blazing-fast candidate screening and multi-signal plagiarism detection.
    Completes in under 10 seconds for 200+ repositories (22,000+ comparison pairs).
    """
    if not os.path.exists(download_folder):
        return {"success": False, "message": "No downloads folder found.", "results": []}

    repo_folders = [
        d for d in os.listdir(download_folder)
        if os.path.isdir(os.path.join(download_folder, d))
    ]

    total_repos = len(repo_folders)
    if total_repos < 2:
        return {"success": False, "message": f"Need at least 2 repos to compare. Found {total_repos}.", "results": []}

    total_pairs = total_repos * (total_repos - 1) // 2
    update_progress(1, 100, f"Indexing {total_repos} student submissions...")

    # Phase 1: Parallel Repository Parsing (0% - 30%)
    meta_list = [{'folder': f, 'download_folder': download_folder} for f in repo_folders]
    workers = min(16, (os.cpu_count() or 4) * 2)

    repos = []
    indexed_count = 0
    with ThreadPoolExecutor(max_workers=workers) as executor:
        for repo_obj in executor.map(process_single_repo, meta_list):
            repos.append(repo_obj)
            indexed_count += 1
            if indexed_count % 15 == 0 or indexed_count == total_repos:
                pct = int((indexed_count / total_repos) * 30)
                update_progress(pct, 100, f"Parsed student code ({indexed_count}/{total_repos})...")

    update_progress(32, 100, f"Screening {total_pairs:,} comparison pairs...")

    # Phase 2: Inverted Index & Ultra-Fast Candidate Generation (30% - 45%)
    md5_to_repos = defaultdict(list)
    line_to_repos = defaultdict(list)

    for idx, r in enumerate(repos):
        for h in r['hash_set']:
            md5_to_repos[h].append(idx)
        # Subsample line hashes for blazing candidate generation
        for lh in list(r['lines'])[:250]:
            line_to_repos[lh].append(idx)

    candidate_pairs = set()

    # Exact file duplicates
    for h, r_list in md5_to_repos.items():
        if len(r_list) > 1:
            for i in range(len(r_list)):
                for j in range(i + 1, len(r_list)):
                    candidate_pairs.add((min(r_list[i], r_list[j]), max(r_list[i], r_list[j])))

    # Code line overlap (ignore shared boilerplate appearing in > 40 repos)
    pair_line_shared = defaultdict(int)
    for lh, r_list in line_to_repos.items():
        if 1 < len(r_list) < 40:
            for i in range(len(r_list)):
                for j in range(i + 1, len(r_list)):
                    pair_line_shared[(min(r_list[i], r_list[j]), max(r_list[i], r_list[j]))] += 1

    for pair, shared_cnt in pair_line_shared.items():
        if shared_cnt >= 12:
            candidate_pairs.add(pair)

    candidate_list = list(candidate_pairs)
    total_candidates = len(candidate_list)
    update_progress(45, 100, f"Evaluating {total_candidates} high-similarity candidates...")

    # Phase 3: Detailed Candidate Scoring (45% - 95%)
    similarities = []
    last_update_t = time.time()

    for idx, (i, j) in enumerate(candidate_list):
        ra, rb = repos[i], repos[j]

        # 1. MD5 Exact File Matching
        common_h = ra['hash_set'] & rb['hash_set']
        total_f = max(ra['file_count'], rb['file_count'], 1)
        md5_score = round(len(common_h) / total_f * 100, 1)

        sample_matches = []
        high_value_exact = 0
        if common_h:
            h2pa = {h: p for p, h in ra['file_hashes'].items()}
            for pb, h in rb['file_hashes'].items():
                if h in common_h and h in h2pa:
                    fa = h2pa[h]
                    ext_a = os.path.splitext(fa)[1].lower()
                    is_hv = ext_a in HIGH_VALUE_EXTENSIONS
                    if is_hv:
                        high_value_exact += 1
                    if len(sample_matches) < 8:
                        sample_matches.append({
                            'file_a': fa, 'file_b': pb, 'score': 100.0, 'is_high_value': is_hv
                        })

        # 2. AST Structure Matching
        ast_scores = []
        if ra['ast_map'] and rb['ast_map']:
            for fa, sa in ra['ast_map'].items():
                base_a = os.path.basename(fa)
                for fb, sb in rb['ast_map'].items():
                    if fa == fb or base_a == os.path.basename(fb):
                        union_len = len(sa | sb)
                        if union_len:
                            jacc = len(sa & sb) / union_len * 100
                            if jacc >= 30:
                                ast_scores.append(jacc)
                                if len(sample_matches) < 8 and not any(m['file_a'] == fa for m in sample_matches):
                                    sample_matches.append({
                                        'file_a': fa, 'file_b': fb, 'score': round(jacc, 1),
                                        'is_high_value': True
                                    })
        ast_score = round(sum(ast_scores) / len(ast_scores), 1) if ast_scores else None

        # 3. Line/Token Text Similarity
        txt_score = 0
        if ra['lines'] and rb['lines']:
            u = len(ra['lines'] | rb['lines'])
            if u:
                txt_score = round(len(ra['lines'] & rb['lines']) / u * 100, 1)

        # Combined Score & Risk Rating
        score_candidates = [md5_score]
        if ast_score is not None:
            score_candidates.append(ast_score)
        if txt_score:
            score_candidates.append(txt_score)

        comb = round(max(score_candidates), 1)
        if comb < 25:
            continue

        if comb >= 80:
            risk = 'critical'
        elif comb >= 50:
            risk = 'high'
        else:
            risk = 'medium'

        # Strict Academic Rules
        triggered_rules = []
        if high_value_exact >= 2 or len(common_h) >= 3 or (len(common_h) >= 1 and total_f <= 2):
            triggered_rules.append("Rule 1: Exact Copy")
        if ast_score and ast_score >= 75 and txt_score >= 60:
            triggered_rules.append("Rule 2: Structural Copy")
        if (md5_score >= 35 or txt_score >= 35):
            triggered_rules.append("Rule 3: Partial Core Copy")
        if ast_score and ast_score >= 70 and txt_score >= 65:
            triggered_rules.append("Rule 4: Multi-Signal Agreement")

        is_plag = (risk in ('critical', 'high')) or len(triggered_rules) >= 1
        confidence = 'very_high' if (risk == 'critical' or len(triggered_rules) >= 2) else ('high' if is_plag else 'medium')

        reason = f"{risk.capitalize()} similarity detected ({comb}%)"
        if triggered_rules:
            reason += f" - {', '.join(triggered_rules)}"

        similarities.append({
            'student_a': {
                'name': ra['name'], 'reg_no': ra['reg_no'], 'sheet': ra['sheet'],
                'file_count': ra['file_count'], 'scan_path': ra['scan_path'],
                'ai_score': ra['ai_score'], 'ai_markers': ra['ai_markers']
            },
            'student_b': {
                'name': rb['name'], 'reg_no': rb['reg_no'], 'sheet': rb['sheet'],
                'file_count': rb['file_count'], 'scan_path': rb['scan_path'],
                'ai_score': rb['ai_score'], 'ai_markers': rb['ai_markers']
            },
            'combined_score': comb,
            'risk': risk,
            'md5_score': md5_score,
            'ast_score': ast_score,
            'text_score': txt_score,
            'matching_files_md5': len(common_h),
            'ast_comparisons': len(ast_scores),
            'text_comparisons': 1 if txt_score else 0,
            'sample_matches': sample_matches,
            'is_plagiarism': is_plag,
            'confidence': confidence,
            'reason': reason,
            'triggered_rules': triggered_rules
        })

        # Throttle progress reporting every 150ms
        now = time.time()
        if now - last_update_t >= 0.15 or (idx + 1) == total_candidates:
            last_update_t = now
            pct = 45 + int(((idx + 1) / max(total_candidates, 1)) * 54)
            update_progress(min(99, pct), 100, f"Scored candidate pairs ({idx + 1}/{total_candidates})...")

    # Sort flagged similarities by highest risk first
    similarities.sort(key=lambda x: (
        0 if x['risk'] == 'critical' else (1 if x['risk'] == 'high' else 2),
        -x['combined_score']
    ))

    update_progress(100, 100, f"Analysis complete! ({len(similarities)} suspicious pairs)")

    return {
        "success": True,
        "total_repos": total_repos,
        "total_pairs": total_pairs,
        "suspicious_pairs": len(similarities),
        "similarities": similarities
    }

def generate_excel_report(latest_results):
    """Generates bytes for the Excel Plagiarism Report with complete metadata."""
    try:
        output = io.BytesIO()
        data = []

        for s in latest_results:
            if s.get('combined_score', 0) < 25:
                continue

            a = s['student_a']
            b = s['student_b']
            path_a = "file:///" + a['scan_path'].replace('\\', '/')
            path_b = "file:///" + b['scan_path'].replace('\\', '/')

            ai_a = "YES" if a.get('ai_score', 0) >= 25 else "No"
            ai_b = "YES" if b.get('ai_score', 0) >= 25 else "No"

            if s.get('sample_matches'):
                for match in s['sample_matches']:
                    data.append({
                        "Student A Name": a['name'],
                        "Student A Reg No": a['reg_no'],
                        "AI Detected A": ai_a,
                        "Student B Name": b['name'],
                        "Student B Reg No": b['reg_no'],
                        "AI Detected B": ai_b,
                        "Risk Level": s['risk'].upper(),
                        "Combined Score (%)": s['combined_score'],
                        "Plagiarism Detected": "YES" if s.get('is_plagiarism') else "NO",
                        "Confidence": s.get('confidence', '').upper(),
                        "Triggered Rules": ", ".join(s.get('triggered_rules', [])),
                        "Matching File in A": match.get('file_a', ''),
                        "Matching File in B": match.get('file_b', ''),
                        "Match Score (%)": match.get('score', 100),
                        "Student A Folder": path_a,
                        "Student B Folder": path_b
                    })
            else:
                data.append({
                    "Student A Name": a['name'],
                    "Student A Reg No": a['reg_no'],
                    "AI Detected A": ai_a,
                    "Student B Name": b['name'],
                    "Student B Reg No": b['reg_no'],
                    "AI Detected B": ai_b,
                    "Risk Level": s['risk'].upper(),
                    "Combined Score (%)": s['combined_score'],
                    "Plagiarism Detected": "YES" if s.get('is_plagiarism') else "NO",
                    "Confidence": s.get('confidence', '').upper(),
                    "Triggered Rules": ", ".join(s.get('triggered_rules', [])),
                    "Matching File in A": "General Similarity",
                    "Matching File in B": "General Similarity",
                    "Match Score (%)": s['combined_score'],
                    "Student A Folder": path_a,
                    "Student B Folder": path_b
                })

        with pd.ExcelWriter(output, engine='xlsxwriter') as writer:
            if data:
                df = pd.DataFrame(data)
                df.to_excel(writer, sheet_name='Plagiarism Report', index=False)
                worksheet = writer.sheets['Plagiarism Report']
                worksheet.autofilter(0, 0, len(df), len(df.columns) - 1)
                for col in range(len(df.columns)):
                    worksheet.set_column(col, col, 20)
                worksheet.set_column(11, 12, 40)
            else:
                pd.DataFrame([{"Message": "No suspicious file pairs found above 25% threshold."}]).to_excel(writer, index=False)

        return output.getvalue(), None
    except Exception as e:
        return None, str(e)
